begin;
create extension if not exists pgtap with schema extensions;
select no_plan();
select ok(not has_table_privilege('authenticated','private.p8_webhook_admission','select'),'Rider cannot read global limiter');
select ok(not has_table_privilege('service_role','private.p8_webhook_admission_leases','insert'),'service cannot directly write leases');
select ok(not has_function_privilege('authenticated','public.backend_acquire_test_webhook_admission()','execute'),'Rider cannot acquire leases');
create temp table tokens(id uuid);
grant all on tokens to service_role;
select set_config('request.jwt.claim.role','service_role',true);
set local role service_role;
insert into tokens select public.backend_acquire_test_webhook_admission() from generate_series(1,8);
select is((select count(id) from tokens),8::bigint,'eight concurrent slots available globally');
select is(public.backend_acquire_test_webhook_admission(),null::uuid,'ninth concurrent lease denied');
select is(public.backend_release_test_webhook_admission((select id from tokens limit 1)),true,'lease released once');
select is(public.backend_release_test_webhook_admission((select id from tokens limit 1)),false,'duplicate release not accepted');
select isnt(public.backend_acquire_test_webhook_admission(),null::uuid,'released slot available');
reset role;
delete from private.p8_webhook_admission_leases;
update private.p8_webhook_admission set accepted=0,window_started_at=clock_timestamp();
set local role service_role;
do $$ declare x uuid; i int; begin for i in 1..60 loop x:=public.backend_acquire_test_webhook_admission(); if x is null or not public.backend_release_test_webhook_admission(x) then raise exception 'unexpected denial'; end if; end loop; end $$;
select is(public.backend_acquire_test_webhook_admission(),null::uuid,'shared minute quota enforced despite released slots');
reset role;
delete from private.p8_webhook_admission;
set local role service_role;
select throws_ok($$select public.backend_acquire_test_webhook_admission()$$,'55000',null,'missing shared state fails closed');
reset role;
select * from finish();
rollback;
