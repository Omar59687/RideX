begin;
create extension if not exists pgtap with schema extensions;
select no_plan();
set local role authenticated;
select throws_ok($$select public.backend_card_matching_enabled()$$,'42501',null,'Rider cannot query server gate');
reset role;
select set_config('request.jwt.claim.role','service_role',true);
set local role service_role;
select is(public.backend_card_matching_enabled(),false,'server reads default OFF');
select throws_ok($$update private.p8_card_matching_gate set enabled=true$$,'42501',null,'server role cannot enable gate');
reset role;
update private.p8_card_matching_gate set enabled=true;
set local role service_role;
select is(public.backend_card_matching_enabled(),true,'server reads actual ON state');
reset role;
delete from private.p8_card_matching_gate;
set local role service_role;
select is(public.backend_card_matching_enabled(),false,'missing gate fails closed');
reset role;
select * from finish();
rollback;
